"""AC and battery idle timings: choose, render, apply.

hypridle cannot switch profiles by itself, so DarkOS keeps two sets of timings
in settings.json and writes the active set to ~/.config/hypr/hypridle.conf,
which hypridle prefers over the shipped /etc/xdg/hypr/hypridle.conf.
darkos-power-watch.py re-applies when the power source changes; Settings
re-applies when you change a timing.

Only lock and suspend are offered. The shipped config must never turn the
display off by itself (ci/verify-iso.sh forbids it: hypridle did that while
hyprlock held the session lock and left VMware guests on a black screen), and
this generated file keeps the same rule. DarkOS always locks before it
sleeps, through before_sleep_cmd.

No GTK here, and sysfs / the output path / the restart are injectable, so all
of it runs against a fake tree in tests.
"""
import os
import re
import subprocess
import tempfile
import time
from dataclasses import dataclass, field

from darkos_shell.user_settings import CHOICES, DEFAULTS

SYSFS = "/sys/class/power_supply"
MAINS_TYPES = ("Mains", "USB")      # USB covers USB-C PD chargers reported as type USB
SOURCES = ("ac", "battery")

GENERAL = """general {
    lock_cmd = pidof hyprlock || /usr/local/bin/darkos-lock
    before_sleep_cmd = loginctl lock-session
    after_sleep_cmd = hyprctl dispatch dpms on
    ignore_dbus_inhibit = false
    ignore_systemd_inhibit = false
}
"""

HEADER = """# Generated by DarkOS (Settings > Power & sleep, darkos-power-watch). Changes here are overwritten.
# Timings for: {label}. Lock and suspend only; the display is never turned off
# by idle while the session is locked.
"""

LABELS = {"ac": "AC power", "battery": "battery"}


@dataclass(frozen=True)
class PowerState:
    source: str          # "ac" or "battery"
    has_battery: bool


@dataclass
class Applied:
    changed: bool
    source: str
    lock: int
    suspend: int
    notes: list = field(default_factory=list)
    restarted: bool = False


def keys_for(source):
    if source not in SOURCES:
        raise ValueError(f"unknown power source: {source!r}")
    return f"idle_{source}_lock", f"idle_{source}_suspend"


def timings_for(settings, source):
    """(lock, suspend) minutes for this source; anything invalid becomes the default."""
    out = []
    for key in keys_for(source):
        value = settings.get(key, DEFAULTS[key])
        if isinstance(value, bool) or not isinstance(value, int) or value not in CHOICES[key]:
            value = DEFAULTS[key]
        out.append(value)
    return out[0], out[1]


def normalize(lock, suspend):
    """Suspend has to come after lock, otherwise it would fire first and the
    lock would never be seen. Returns (lock, suspend, notes)."""
    notes = []
    if lock and suspend and suspend <= lock:
        later = [c for c in CHOICES["idle_ac_suspend"] if c > lock]
        fixed = later[0] if later else 0
        notes.append("Suspend has to come after the screen locks, so it was moved to "
                     + ("never." if fixed == 0 else f"{fixed} minutes."))
        suspend = fixed
    return lock, suspend, notes


def detect(sysfs=SYSFS):
    """Which power source is in use, from /sys/class/power_supply.

    No battery means a desktop: always "ac". With a battery, AC means some
    Mains/USB supply reports online=1.
    """
    has_battery = False
    mains_online = False
    try:
        entries = sorted(os.listdir(sysfs))
    except OSError:
        entries = []
    for entry in entries:
        base = os.path.join(sysfs, entry)
        try:
            with open(os.path.join(base, "type"), "r", encoding="utf-8") as f:
                kind = f.read().strip()
        except OSError:
            continue
        if kind == "Battery":
            # Peripheral batteries (mice, headsets) say scope=Device; they are not the system's.
            try:
                with open(os.path.join(base, "scope"), "r", encoding="utf-8") as f:
                    if f.read().strip() == "Device":
                        continue
            except OSError:
                pass
            has_battery = True
        elif kind in MAINS_TYPES:
            try:
                with open(os.path.join(base, "online"), "r", encoding="utf-8") as f:
                    if f.read().strip() == "1":
                        mains_online = True
            except OSError:
                pass
    if not has_battery or mains_online:
        return PowerState("ac", has_battery)
    return PowerState("battery", has_battery)


def render_hypridle(lock_min, suspend_min, source="ac"):
    parts = [HEADER.format(label=LABELS.get(source, source)), GENERAL]
    for minutes, command in ((lock_min, "loginctl lock-session"), (suspend_min, "systemctl suspend")):
        if minutes:
            parts.append(f"\nlistener {{\n    timeout = {int(minutes) * 60}\n    on-timeout = {command}\n}}\n")
    return "".join(parts)


_LISTENER = re.compile(r"listener\s*\{[^}]*?timeout\s*=\s*(\d+)[^}]*?on-timeout\s*=\s*([^\n]+)", re.S)


def parse_timeouts(text):
    """[(seconds, command)] for every listener in a hypridle config."""
    return [(int(sec), cmd.strip()) for sec, cmd in _LISTENER.findall(text)]


def config_path(home=None):
    base = os.environ.get("XDG_CONFIG_HOME") if home is None else None
    base = base or os.path.join(home or os.environ.get("HOME") or os.path.expanduser("~"), ".config")
    return os.path.join(base, "hypr", "hypridle.conf")


def restart_hypridle(path):
    """Stop the running hypridle and start it on this file. Blocking: call off the GTK thread."""
    try:
        subprocess.run(["pkill", "-x", "hypridle"], capture_output=True, timeout=3)
        time.sleep(0.2)
        subprocess.Popen(["hypridle", "-c", path], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         start_new_session=True)
        return True
    except (OSError, subprocess.SubprocessError):
        return False


def apply_idle_config(settings, source=None, path=None, restart=restart_hypridle, sysfs=SYSFS):
    """Write the timings for `source` (default: the detected one) and restart hypridle if they changed."""
    source = source or detect(sysfs).source
    lock, suspend, notes = normalize(*timings_for(settings, source))
    text = render_hypridle(lock, suspend, source)
    path = path or config_path()
    try:
        with open(path, "r", encoding="utf-8") as f:
            if f.read() == text:
                return Applied(False, source, lock, suspend, notes)
    except OSError:
        pass
    directory = os.path.dirname(path)
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".hypridle.", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except OSError:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return Applied(True, source, lock, suspend, notes, restarted=bool(restart(path)))


def minutes_label(minutes):
    if not minutes:
        return "Never"
    if minutes % 60 == 0:
        hours = minutes // 60
        return "1 hour" if hours == 1 else f"{hours} hours"
    return "1 minute" if minutes == 1 else f"{minutes} minutes"
