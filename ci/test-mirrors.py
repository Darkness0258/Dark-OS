def save_path(argv):
    return argv[argv.index("--save") + 1]


class FakeReflector:
    """Writes `texts[i]` to --save on call i (the last one repeats); can fail in the ways reflector does."""

    def __init__(self, *texts, code=0, err="", raises=None):
        self.texts, self.code, self.err, self.raises = list(texts), code, err, raises
        self.calls = []

    def __call__(self, argv, timeout=150):
        self.calls.append(list(argv))
        if self.raises:
            raise self.raises
        if self.code == 0:
            text = self.texts[min(len(self.calls), len(self.texts)) - 1]
            Path(save_path(argv)).write_text(text)
        return self.code, "", self.err


class Dirs(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self._tmp.name) / "pacman.d"
        self.dir.mkdir()
        self.ml = str(self.dir / "mirrorlist")
        self.bk = str(self.dir / "mirrorlist.darkos-bak")
        Path(self.ml).write_text(STOCK)

    def tearDown(self):
        self._tmp.cleanup()

    def rank(self, fake, **kw):
        kw.setdefault("now", NOW)
        return mirrors.rank(mirrorlist=self.ml, backup=self.bk, run=fake, require_root=False, **kw)

    def stock_untouched(self):
        self.assertEqual(Path(self.ml).read_text(), STOCK, "the existing mirror list must not change")
        self.assertEqual(sorted(os.listdir(self.dir)), sorted(set(os.listdir(self.dir)) & {"mirrorlist", "mirrorlist.darkos-bak"}),
                         "no temp files may be left behind")


class ValidationTests(unittest.TestCase):
    def test_a_reflector_style_list_is_valid(self):
        self.assertEqual(mirrors.validate_list(GOOD), (True, ""))
        self.assertEqual(len(mirrors.parse_servers(GOOD)), 4)

    def test_too_few_distinct_mirrors(self):
        ok, why = mirrors.validate_list(TWO)
        self.assertFalse(ok)
        self.assertIn("only 2 usable mirrors", why)
        dup = "Server = https://a.example/$repo/os/$arch\n" * 5
        self.assertFalse(mirrors.validate_list(dup)[0], "five copies of one mirror are one mirror")

    def test_nothing_but_https_server_lines_and_comments_is_accepted(self):
        for evil in ("Include = /etc/pacman.d/other\n", "Server = http://plain.example/$repo/os/$arch\n",
                     "Server = https://x.example/no-placeholders\n", "CacheServer = https://c.example/\n",
                     "Server = https://a.example/$repo/os/$arch; rm -rf /\n", "Server = file:///tmp/x/$repo/$arch\n"):
            ok, _why = mirrors.validate_list(GOOD + evil)
            self.assertFalse(ok, evil)

    def test_a_restore_only_needs_one_active_mirror(self):
        self.assertTrue(mirrors.validate_list(STOCK, minimum=1)[0])
        self.assertFalse(mirrors.validate_list("# nothing enabled\n", minimum=1)[0])

    def test_countries_and_count_are_checked_against_fixed_values(self):
        self.assertEqual(mirrors.clean_countries(["de", " fr ", "DE"]), ("DE", "FR"))
        for bad in (["XX"], ["Germany"], ["DE;reboot"], ["--save"], [""], ["../x"]):
            with self.assertRaises(ValueError, msg=bad):
                mirrors.clean_countries(bad)
        self.assertEqual(mirrors.clean_number(10), 10)
        for bad in (2, 31, "10", True, None, 10.5):
            with self.assertRaises(ValueError, msg=bad):
                mirrors.clean_number(bad)

    def test_reflector_argument_list(self):
        argv = mirrors.build_reflector_argv("/tmp/x", ("DE", "FR"), 8)
        self.assertEqual(argv[0], "reflector")
        self.assertEqual(argv[argv.index("--protocol") + 1], "https")
        self.assertEqual(argv[argv.index("--country") + 1], "DE,FR")
        self.assertEqual(argv[argv.index("--number") + 1], "8")
        self.assertIn("--age", argv)
        relaxed = mirrors.build_reflector_argv("/tmp/x", (), 10, relaxed=True)
        self.assertNotIn("--age", relaxed)
        self.assertNotIn("--country", relaxed)


class RankTests(Dirs):
    def test_success_installs_the_list_backs_up_the_old_one_and_leaves_no_litter(self):
        result = self.rank(FakeReflector(GOOD), countries=("DE",))
        text = Path(self.ml).read_text()
        self.assertTrue(text.startswith("# Ranked by DarkOS on 2026-11-07T12:00:00Z"))
        self.assertIn("countries: DE", text.splitlines()[0])
        self.assertEqual(mirrors.parse_servers(text), mirrors.parse_servers(GOOD))
        self.assertEqual(Path(self.bk).read_text(), STOCK, "the previous list is kept for Restore")
        self.assertEqual((result.mirrors, result.fastest, result.countries, result.relaxed),
                         (4, "mirror.one.example", ("DE",), False))
        self.assertEqual(stat.S_IMODE(os.stat(self.ml).st_mode), 0o644)
        self.assertEqual(sorted(os.listdir(self.dir)), ["mirrorlist", "mirrorlist.darkos-bak"])

    def test_too_few_mirrors_retries_without_the_24_hour_filter(self):
        fake = FakeReflector(TWO, GOOD)
        result = self.rank(fake)
        self.assertTrue(result.relaxed)
        self.assertEqual(len(fake.calls), 2)
        self.assertIn("--age", fake.calls[0])
        self.assertNotIn("--age", fake.calls[1])

    def test_still_too_few_changes_nothing(self):
        with self.assertRaises(mirrors.MirrorError) as ctx:
            self.rank(FakeReflector(TWO))
        self.assertIn("enough good mirrors", str(ctx.exception))
        self.stock_untouched()
        self.assertFalse(os.path.exists(self.bk))

    def test_reflector_failing_changes_nothing_and_says_why_without_a_second_long_wait(self):
        fake = FakeReflector(code=1, err="warning: x\nerror: could not retrieve mirror data\n")
        with self.assertRaises(mirrors.MirrorError) as ctx:
            self.rank(fake)
        self.assertIn("could not retrieve mirror data", str(ctx.exception))
        self.assertEqual(len(fake.calls), 1, "a network failure must not be retried at 150 s a time")
        self.stock_untouched()

    def test_a_timeout_or_missing_reflector_changes_nothing(self):
        for exc in (mirrors.MirrorError("Ranking took too long and was stopped. Your mirror list was not changed."),
                    mirrors.MirrorError("reflector is not installed.")):
            with self.assertRaises(mirrors.MirrorError):
                self.rank(FakeReflector(raises=exc))
            self.stock_untouched()

    def test_a_poisoned_list_is_refused(self):
        with self.assertRaises(mirrors.MirrorError):
            self.rank(FakeReflector(GOOD + "Include = /etc/shadow\n"))
        self.stock_untouched()

    def test_not_being_root_is_refused_before_anything_runs(self):
        fake = FakeReflector(GOOD)
        with self.assertRaises(mirrors.MirrorError) as ctx:
            mirrors.rank(mirrorlist=self.ml, backup=self.bk, run=fake, euid=lambda: 1000)
        self.assertIn("administrator", str(ctx.exception))
        self.assertEqual(fake.calls, [])

    def test_bad_arguments_never_reach_reflector(self):
        fake = FakeReflector(GOOD)
        for kw in ({"countries": ("XX",)}, {"number": 99}):
            with self.assertRaises(ValueError):
                self.rank(fake, **kw)
        self.assertEqual(fake.calls, [])

    def test_an_unwritable_backup_aborts_before_the_list_is_replaced(self):
        Path(self.dir / "blocked").write_text("a file, not a directory")
        with self.assertRaises(OSError):
            mirrors.rank(mirrorlist=self.ml, backup=str(self.dir / "blocked" / "bk"),
                         run=FakeReflector(GOOD), require_root=False, now=NOW)
        self.assertEqual(Path(self.ml).read_text(), STOCK)

    def test_the_real_runner_reports_a_missing_reflector_and_a_timeout(self):
        orig = mirrors.subprocess.run
        try:
            def missing(*a, **k):
                raise FileNotFoundError("reflector")

            def slow(*a, **k):
                raise subprocess.TimeoutExpired("reflector", 1)

            mirrors.subprocess.run = missing
            with self.assertRaisesRegex(mirrors.MirrorError, "not installed"):
                mirrors.default_run(["reflector"])
            mirrors.subprocess.run = slow
            with self.assertRaisesRegex(mirrors.MirrorError, "too long"):
                mirrors.default_run(["reflector"])
        finally:
            mirrors.subprocess.run = orig


class RestoreAndStatusTests(Dirs):
    def test_restore_puts_the_previous_list_back(self):
        self.rank(FakeReflector(GOOD))
        count = mirrors.restore(self.ml, self.bk, require_root=False)
        self.assertEqual(count, 1)
        self.assertEqual(Path(self.ml).read_text(), STOCK)

    def test_restore_without_a_backup_or_with_a_bad_one_changes_nothing(self):
        with self.assertRaisesRegex(mirrors.MirrorError, "no earlier"):
            mirrors.restore(self.ml, self.bk, require_root=False)
        Path(self.bk).write_text("Include = /etc/passwd\n")
        with self.assertRaisesRegex(mirrors.MirrorError, "not usable"):
            mirrors.restore(self.ml, self.bk, require_root=False)
        self.assertEqual(Path(self.ml).read_text(), STOCK)
        with self.assertRaisesRegex(mirrors.MirrorError, "administrator"):
            mirrors.restore(self.ml, self.bk, euid=lambda: 1000)

    def test_status_of_a_stock_list_a_ranked_list_and_a_missing_file(self):
        info = mirrors.status(self.ml, self.bk)
        self.assertEqual((info.exists, info.servers, info.fastest, info.ranked_at, info.has_backup),
                         (True, 1, "geo.mirror.pkgbuild.com", None, False))
        self.assertIn("Not ranked by DarkOS yet", mirrors.describe(info))
        self.rank(FakeReflector(GOOD))
        info = mirrors.status(self.ml, self.bk)
        self.assertEqual((info.servers, info.fastest, info.has_backup), (4, "mirror.one.example", True))
        self.assertEqual(info.ranked_at, NOW)
        self.assertEqual(mirrors.describe(info, now=NOW), "Ranked today. 4 mirrors, fastest: mirror.one.example.")
        later = datetime(2026, 11, 10, 12, tzinfo=timezone.utc)
        self.assertIn("Ranked 3 days ago", mirrors.describe(info, now=later))
        old = datetime(2027, 1, 20, tzinfo=timezone.utc)
        self.assertIn("worthwhile", mirrors.describe(info, now=old))
        os.unlink(self.ml)
        gone = mirrors.status(self.ml, self.bk)
        self.assertFalse(gone.exists)
        self.assertIn("No mirrors are enabled", mirrors.describe(gone))

    def test_a_mangled_header_is_not_a_crash(self):
        Path(self.ml).write_text("# Ranked by DarkOS on yesterday-ish\n" + GOOD)
        info = mirrors.status(self.ml, self.bk)
        self.assertIsNone(info.ranked_at)
        self.assertEqual(info.servers, 4)


def load_cli():
    spec = importlib.util.spec_from_file_location("darkos_mirrors_cli", BIN / "darkos-mirrors.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class CliTests(Dirs):
    def setUp(self):
        super().setUp()
        self.cli = load_cli()

    def run_cli(self, argv, fake=None, **kw):
        out, err = io.StringIO(), io.StringIO()
        kw.setdefault("euid", lambda: 0)
        code = self.cli.main(argv, out=out, err=err, mirrorlist=self.ml, backup=self.bk,
                             run=fake or FakeReflector(GOOD), now=NOW, **kw)
        return code, out.getvalue(), err.getvalue()

    def test_the_command_line_cannot_name_a_file(self):
        """It runs as root through pkexec: any path option would be 'overwrite any file as root'."""
        options = set()
        parser = self.cli.build_parser()
        options |= {o for a in parser._actions for o in a.option_strings}
        for action in parser._actions:
            for sub in getattr(action, "choices", {}).values() if hasattr(action, "choices") and isinstance(action.choices, dict) else ():
                options |= {o for a in sub._actions for o in a.option_strings}
        self.assertEqual(options, {"-h", "--help", "--json", "--country", "--number"})

    def test_rank_prints_machine_readable_json_for_settings(self):
        code, out, _err = self.run_cli(["rank", "--json", "--country", "de, fr", "--number", "8"])
        data = json.loads(out)
        self.assertEqual(code, 0)
        self.assertTrue(data["ok"])
        self.assertEqual((data["mirrors"], data["countries"]), (4, ["DE", "FR"]))
        self.assertIn("Ranked 4 mirrors", data["message"])

    def test_bad_arguments_exit_2_and_run_nothing(self):
        for argv in (["rank", "--country", "XX;rm -rf /"], ["rank", "--number", "999"], ["rank", "--country", "Germany"]):
            fake = FakeReflector(GOOD)
            code, _out, err = self.run_cli(argv, fake)
            self.assertEqual(code, 2, argv)
            self.assertEqual(fake.calls, [])
            self.assertTrue(err)
        with self.assertRaises(SystemExit) as ctx:
            self.run_cli(["rank", "--output", "/etc/passwd"])
        self.assertEqual(ctx.exception.code, 2)

    def test_failures_exit_1_with_a_json_message(self):
        code, out, _ = self.run_cli(["rank", "--json"], FakeReflector(code=1, err="network is down"))
        self.assertEqual(code, 1)
        self.assertFalse(json.loads(out)["ok"])
        self.assertIn("network is down", json.loads(out)["message"])
        code, out, _ = self.run_cli(["rank", "--json"], euid=lambda: 1000)
        self.assertEqual(code, 1)
        self.assertIn("administrator", json.loads(out)["message"])

    def test_status_and_restore_commands(self):
        code, out, _ = self.run_cli(["status", "--json"])
        self.assertEqual(json.loads(out)["servers"], 1)
        self.run_cli(["rank"])
        code, out, _ = self.run_cli(["restore", "--json"])
        self.assertEqual((code, json.loads(out)["mirrors"]), (0, 1))
        self.assertEqual(Path(self.ml).read_text(), STOCK)

    def test_the_old_entry_point_is_a_thin_wrapper_that_cannot_clobber_the_list(self):
        text = (BIN / "choose-mirror").read_text(encoding="utf-8")
        self.assertIn('exec /usr/local/bin/darkos-mirrors.py rank "$@"', text)
        self.assertNotIn("--save", text)
        self.assertNotIn("/etc/pacman.d/mirrorlist\n", text.replace("# ", ""))
        self.assertEqual(subprocess.run(["bash", "-n", str(BIN / "choose-mirror")]).returncode, 0)


def pump(until, timeout=3.0):
    ctx = GLib.MainContext.default()
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        while ctx.iteration(False):
            pass
        if until():
            return True
        time.sleep(0.01)
    return until()


@unittest.skipUnless(GTK, "no display (run under xvfb-run)")
class MirrorCardTests(unittest.TestCase):
    def setUp(self):
        from darkos_shell import mirror_card
        self.mc = mirror_card
        self.settings = {"mirror_country": ""}
        self.runs = []
        self.threads = set()
        self.info = mirrors.Status(True, 1, "geo.mirror.pkgbuild.com", None, False)
        self.reply = (0, json.dumps({"ok": True, "message": "Ranked 10 mirrors; fastest: fast.example."}) + "\n", "")
        self.gate = None
        self.cards = []

    def tearDown(self):
        for c in self.cards:
            c.destroy()

    def card(self, live=False):
        def run(argv):
            self.runs.append(list(argv))
            self.threads.add(threading.current_thread())
            if self.gate:
                self.gate.wait(3)
            self.info = mirrors.Status(True, 10, "fast.example", NOW, True)
            return self.reply

        c = self.mc.MirrorCard(load=lambda: dict(self.settings),
                               save=lambda d: self.settings.update(d) or True,
                               status=lambda: self.info, run=run, live=live)
        self.cards.append(c)
        return c

    def pick_country(self, card, name):
        for i, row in enumerate(card.country_combo.get_model()):
            if row[0] == name:
                card.country_combo.set_active(i)
                return
        self.fail(name)

    def test_it_shows_the_state_and_only_offers_restore_when_there_is_something_to_restore(self):
        c = self.card()
        self.assertIn("Not ranked by DarkOS yet", c.summary.get_text())
        self.assertTrue(c.rank_btn.get_sensitive())
        self.assertFalse(c.restore_btn.get_sensitive())
        self.info = mirrors.Status(True, 10, "fast.example", NOW, True)
        c.refresh()
        self.assertTrue(c.restore_btn.get_sensitive())

    def test_country_list_starts_with_anywhere_and_covers_the_table(self):
        c = self.card()
        names = [r[0] for r in c.country_combo.get_model()]
        self.assertEqual(names[0], "Anywhere (fastest overall)")
        self.assertEqual(len(names), 1 + len(mirrors.COUNTRIES))
        self.assertEqual(c.selected_country(), "")

    def test_rank_runs_on_a_worker_thread_with_exactly_the_expected_arguments(self):
        c = self.card()
        self.pick_country(c, "Germany")
        c.rank_btn.clicked()
        self.assertTrue(pump(lambda: self.runs))
        self.assertEqual(self.runs[0], ["/usr/local/bin/darkos-mirrors.py", "rank", "--json",
                                        "--number", "10", "--country", "DE"])
        self.assertTrue(pump(lambda: "fastest: fast.example" in c.result.get_text()))
        self.assertNotIn(threading.main_thread(), self.threads)
        self.assertIn("Ranked today", c.summary.get_text(), "the summary re-reads the list after ranking")

    def test_the_card_shows_progress_and_blocks_a_second_click_while_it_works(self):
        self.gate = threading.Event()
        c = self.card()
        c.rank_btn.clicked()
        self.assertIn("Ranking mirrors", c.result.get_text())
        self.assertFalse(c.rank_btn.get_sensitive())
        self.assertFalse(c.country_combo.get_sensitive())
        c.rank()
        c.restore()
        self.gate.set()
        self.assertTrue(pump(lambda: c.rank_btn.get_sensitive()))
        self.assertEqual(len(self.runs), 1, "clicks while busy must not start more runs")

    def test_the_chosen_country_is_remembered(self):
        c = self.card()
        self.pick_country(c, "France")
        c.rank_btn.clicked()
        self.assertEqual(self.settings["mirror_country"], "FR")
        self.assertTrue(pump(lambda: c.rank_btn.get_sensitive()))
        again = self.card()
        self.assertEqual(again.selected_country(), "FR")
        self.settings["mirror_country"] = "not-a-code"
        self.assertEqual(self.card().selected_country(), "")

    def test_failure_text_is_shown_and_nothing_is_claimed(self):
        self.reply = (1, json.dumps({"ok": False, "message": "reflector failed: network is down"}), "")
        c = self.card()
        c.rank_btn.clicked()
        self.assertTrue(pump(lambda: "Not changed:" in c.result.get_text()))
        self.assertIn("network is down", c.result.get_text())

    def test_dismissing_the_password_prompt_is_explained(self):
        self.reply = (126, "", "Error executing command as another user: Not authorized")
        c = self.card()
        c.rank_btn.clicked()
        self.assertTrue(pump(lambda: "Cancelled" in c.result.get_text()))

    def test_restore_calls_the_restore_command(self):
        self.info = mirrors.Status(True, 10, "fast.example", NOW, True)
        self.reply = (0, json.dumps({"ok": True, "message": "Restored the earlier mirror list (1 mirrors)."}), "")
        c = self.card()
        c.restore_btn.clicked()
        self.assertTrue(pump(lambda: self.runs))
        self.assertEqual(self.runs[0], ["/usr/local/bin/darkos-mirrors.py", "restore", "--json"])
        self.assertTrue(pump(lambda: "Restored" in c.result.get_text()))

    def test_on_the_live_iso_the_card_is_inert_and_says_why(self):
        c = self.card(live=True)
        self.assertIn("live ISO", c.summary.get_text())
        for w in (c.rank_btn, c.restore_btn, c.country_combo):
            self.assertFalse(w.get_sensitive())
        c.rank()
        self.assertEqual(self.runs, [])

    def test_message_parsing(self):
        m = self.mc.message_from
        self.assertEqual(m(0, 'noise\n{"ok": true, "message": "fine"}\n', ""), (True, "fine"))
        self.assertEqual(m(1, '{"ok": false, "message": "no"}', ""), (False, "no"))
        self.assertEqual(m(126, "", ""), (False, "Cancelled: administrator rights are needed to change the mirror list."))
        self.assertEqual(m(1, "", "boom\nlast line"), (False, "last line"))
        self.assertEqual(m(3, "", ""), (False, "It did not finish (exit 3)."))

    def test_pkexec_is_the_only_way_in_and_its_absence_is_reported(self):
        seen = []
        orig = self.mc.subprocess.run
        try:
            def fake(argv, **kw):
                seen.append(argv)
                raise FileNotFoundError("pkexec")
            self.mc.subprocess.run = fake
            code, _out, err = self.mc.privileged_run(["/usr/local/bin/darkos-mirrors.py", "rank"])
        finally:
            self.mc.subprocess.run = orig
        self.assertEqual(seen[0][:2], ["pkexec", "/usr/local/bin/darkos-mirrors.py"])
        self.assertEqual(code, 127)
        self.assertIn("pkexec", err)

    def test_settings_hosts_the_card_on_the_updates_page(self):
        source = (BIN / "darkos-settings.py").read_text(encoding="utf-8")
        self.assertIn("self.mirror_card = MirrorCard(live=live)", source)
        self.assertIn('elif row.category_id == "updates":\n                self.mirror_card.refresh()', source)


