#!/usr/bin/env python3
"""Render every static theme file from the Calm Dark palette.

The shell and the GTK apps read tokens at runtime. Waybar, mako, ReGreet,
hyprlock, Hyprland and Calamares can't, so their colours are generated here
from the same palette (darkos_shell/palette.py) and checked in CI:

    python3 tools/gen-theme.py          # rewrite the files
    python3 tools/gen-theme.py --check  # exit 1 if any file has drifted

Whole files (waybar/style.css, mako/config, regreet.css) are rendered from
templates. Hand-maintained files (hyprlock.conf, hyprland.conf, Calamares
branding) only have their colour lines rewritten.

These files use the *default* accent. A custom accent set in Settings
re-colours the shell and the apps but not these (they are static files).
"""
import argparse
import importlib.util
import re
import string
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AIROOTFS = ROOT / "airootfs"

_spec = importlib.util.spec_from_file_location(
    "darkos_palette", AIROOTFS / "usr/local/bin/darkos_shell/palette.py"
)
palette = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(palette)

P = palette.generate_palette("#00e5ff")
ACCENT = P["accent"]


def rgba(hex_value, alpha):
    r, g, b = palette.hex_to_rgb(hex_value)
    return f"rgba({r}, {g}, {b}, {alpha})"


def alpha_hex(hex_value, alpha):
    """'#rrggbb' + 0-1 alpha -> '#rrggbbaa' (mako) ."""
    return f"{hex_value}{round(alpha * 255):02x}"


def bare(hex_value):
    return hex_value.lstrip("#")


